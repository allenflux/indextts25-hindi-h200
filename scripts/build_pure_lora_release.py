sys.dont_write_bytecode = True
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
_spec = importlib.util.spec_from_file_location("_pure_release_public_helpers", ROOT / "scripts/prepare_hf_release.py")
public = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(public)
from hi_h200_native import synth
from hi_h200_native.adapter_synth import pure_parameters
from hi_h200_native.assets import (MODEL_REPO, MODEL_REVISION, W2V_REPO, CAMP_REPO, LICENSES, selected_assets)

TOKENIZER = public.TOKENIZER
EXTRAS = ("asset-plan.json", "w2v-bert-2.0.manifest.json", "campplus.manifest.json")
# Exact original payload names selected for public metadata, never a directory copy.
METADATA = ("config.yaml", TOKENIZER, "LICENSE", "README.md", "hf_cache/w2v-bert-2.0/config.json",
            "hf_cache/w2v-bert-2.0/preprocessor_config.json", "hf_cache/w2v-bert-2.0/README.md", "hf_cache/campplus/README.md")
MAX_ADAPTER = 32 * 1024**2
BASE_NOTE = """# Exact training-base metadata, without base weights

model-manifest.json is the exact original 16-entry training manifest. The
asset-plan.json and two auxiliary *.manifest.json files were generated by this
project's asset preparation helper; they are not files claimed to exist in the
upstream Hugging Face repository. Their original bytes preserve adapter identity.

Only the named public configuration, tokenizer, model cards, license and generated
metadata are included here. Original GPT, semantic/codec/CAMPPlus/w2v weights and
statistics tensors are NOT distributed. Obtain the separately licensed pinned
assets with the project asset tools; verify all expected bytes before loading.
Preserve this original training manifest separately from the full synthesis
manifest. Never replace it with a new manifest or weaken adapter identity checks.
This package is native-format A/B only, not a generic PEFT/ComfyUI LoRA bundle.
"""


@dataclass(frozen=True)
class Pins:
    adapter_sha256: str
    adapter_bytes: int
    base_manifest_sha256: str
    step: int
    layers: int
    model_dim: int
    assets: tuple
    scope: str = "production_frozen_pilot48"


PRODUCTION = Pins("15c080715b3b50bf38b33a70f196a9c9e987446e0a6bb87b2e0c8b7835f57dbd", 5931907,
    "11dae1733635a0d46e7edbc7c5444900fed2bbb4450767aa4d2820b2221f0e6f", 100, 24, 1280, tuple(selected_assets("extract")))


def require(value, message):
    if not value:
        raise ValueError(message)


def encode(value):
    return (json.dumps(value, sort_keys=True, ensure_ascii=False, indent=2, allow_nan=False) + "\n").encode()


def local(path, workspace, *, card=False):
    raw = Path(path).absolute()
    require(raw.resolve(strict=True) == raw and raw.is_file() or raw.resolve(strict=True) == raw and raw.is_dir(),
            "Inputs must use canonical regular files/directories without symlinks")
    require(not any(part in {".git", ".ssh", ".aws", ".huggingface", "hf-home", ".hf-home"} for part in raw.parts),
            "Authentication/Git internals are not release inputs")
    require(raw.is_relative_to(workspace) or card and raw.is_relative_to(ROOT / "docs"),
            "Inputs must stay in WORK; only the explicitly reviewed repository card may be external")
    return raw


def read_public(path):
    return public.public_text(path)


def snapshot(path):
    info = path.stat()
    return (info.st_dev, info.st_ino, info.st_size, info.st_mtime_ns, info.st_ctime_ns)


def inspect(args, *, _pins=PRODUCTION):
    """Private fixture pins are test-only; CLI always passes the production pins."""
    work = Path(args.workspace_root).resolve(strict=True)
    require(work.is_dir() and work != Path(work.anchor), "Use a dedicated existing WORK")
    source, assets, manifest, adapter = (local(value, work) for value in
        (args.official_repo, args.model_dir, args.base_manifest, args.adapter))
    card = local(args.model_card, work, card=True)
    output = Path(args.output_dir).absolute()
    require(not output.exists() and not output.is_symlink() and output.parent.resolve(strict=True) == output.parent
            and output.is_relative_to(work), "Output must be fresh with a canonical existing parent inside WORK")
    protected = (ROOT.resolve(), source, assets, manifest, adapter, card)
    require(not any(output == path or output.is_relative_to(path) or path.is_relative_to(output) for path in protected),
            "Release output overlaps source/model/inputs/project")
    require(manifest.is_relative_to(assets), "Original base manifest must be inside original model assets")
    require(args.adapter_sha256 == _pins.adapter_sha256 and args.base_manifest_sha256 == _pins.base_manifest_sha256,
            "Only the independently frozen pilot48 adapter and original manifest are eligible")
    require(adapter.is_file() and adapter.stat().st_size == _pins.adapter_bytes <= MAX_ADAPTER
            and synth.sha256(adapter) == args.adapter_sha256, "Adapter size/SHA mismatch")
    synth.verify_source(source)
    require(synth.sha256(manifest) == args.base_manifest_sha256, "Exact original training manifest SHA mismatch")
    record = public.bounded_json(manifest)
    expected = {item.relative_path: item for item in _pins.assets}
    require(set(record) == {"repository", "snapshot_revision", "files"} and record["repository"] == MODEL_REPO
            and record["snapshot_revision"] == MODEL_REVISION and isinstance(record["files"], dict)
            and set(record["files"]) == set(expected) | set(EXTRAS), "Expected exact original 16-entry public base manifest")
    for name, digest in record["files"].items():
        require(isinstance(digest, str) and re.fullmatch(r"[0-9a-f]{64}", digest), "Invalid base file digest")
        if name in expected and expected[name].hash_kind == "sha256":
            require(digest == expected[name].digest, "Base weight reference differs from fixed public metadata")
    operations = {"adapter.pt": (adapter, args.adapter_sha256), "base-metadata/model-manifest.json": (manifest, args.base_manifest_sha256)}
    for name in (*METADATA, *EXTRAS):
        path = local(assets / name, work)
        require(path.is_file() and path.stat().st_size <= 2 * 1024**2
                and synth.sha256(path) == record["files"][name], "Public base metadata mismatch")
        if name in METADATA:
            item = expected[name]
            public.pinned_bytes(path, item.size, item.hash_kind, item.digest)
        if name != TOKENIZER:
            read_public(path)
        operations["base-metadata/" + name] = (path, record["files"][name])
    plan = public.bounded_json(assets / "asset-plan.json")
    require(set(plan) == {"schema_version", "stage", "metadata_verified", "downloaded", "network_payload_bytes", "files", "licenses", "permission_scope", "endpoint", "auth", "budget_scope"}
            and plan["schema_version"] == 1 and plan["stage"] == "extract" and plan["metadata_verified"] is True
            and plan["downloaded"] is False and plan["files"] == [asdict(item) for item in _pins.assets]
            and plan["network_payload_bytes"] == sum(item.size for item in _pins.assets), "Generated extraction plan differs from the fixed public payload references")
    for repository, name in ((W2V_REPO, EXTRAS[1]), (CAMP_REPO, EXTRAS[2])):
        items = [item for item in _pins.assets if item.repository == repository]
        auxiliary = public.bounded_json(assets / name)
        require(auxiliary == {"repository": repository, "snapshot_revision": items[0].revision, "license": LICENSES[repository],
                "files": {item.relative_path: record["files"][item.relative_path] for item in items}}, "Generated auxiliary manifest differs")
    require(re.fullmatch(r"[0-9a-f]{64}", args.model_card_sha256) and synth.sha256(card) == args.model_card_sha256,
            "Independently reviewed model-card SHA required")
    card_bytes = public.reviewed_card(card)
    require(not re.search(r"模型卡草稿|草稿状态|待填|待实际|TODO|PLACEHOLDER|\bDRAFT\b", card_bytes.decode(), re.I),
            "Draft/placeholder model cards cannot be packaged")
    for name, (size, digest) in public.CODE_LICENSES.items():
        path = local(source / name, work)
        public.pinned_bytes(path, size, "sha256", digest)
        operations[name] = (path, digest)
    operations.update({"README.md": (card, args.model_card_sha256), "MODEL_LICENSE": (assets / "LICENSE", record["files"]["LICENSE"])})
    import yaml
    config = yaml.safe_load((assets / "config.yaml").read_text())
    require(isinstance(config, dict) and str(config.get("version")) == "2.5" and config["gpt"]["layers"] == _pins.layers
            and config["gpt"]["model_dim"] == _pins.model_dim, "Fixed official architecture differs")
    identity = {"official_commit": synth.OFFICIAL_COMMIT, "model_repository": MODEL_REPO, "model_snapshot_revision": MODEL_REVISION,
        "model_manifest_sha256": args.base_manifest_sha256, "model_files": dict(record["files"]),
        "config_sha256": record["files"]["config.yaml"], "tokenizer_sha256": record["files"][TOKENIZER]}
    zip_output = None
    if args.zip_output is not None:
        zip_output = Path(args.zip_output).absolute()
        require(zip_output.suffix == ".zip" and not zip_output.exists() and not zip_output.is_symlink()
                and zip_output.parent.resolve(strict=True) == zip_output.parent and zip_output.is_relative_to(work), "ZIP output must be a fresh canonical .zip path inside WORK")
        require(not any(zip_output == path or zip_output.is_relative_to(path) or path.is_relative_to(zip_output) for path in (*protected, output)),
                "ZIP output overlaps protected input/release")
    summary = {"schema_version": 1, "kind": "pure_attention_lora_public_package", "adapter_sha256": args.adapter_sha256,
        "adapter_bytes": adapter.stat().st_size, "step": _pins.step, "official_source_commit": synth.OFFICIAL_COMMIT,
        "base_model_revision": MODEL_REVISION, "base_manifest_sha256": args.base_manifest_sha256,
        "model_card_sha256": args.model_card_sha256, "base_weights_opened_or_copied": False,
        "package_scope": _pins.scope, "adapter_tensor_validation": False, "quality_verified": False, "production_deployed": False,
        "gpu_validation_performed_by_builder": False, "training_metrics_source": "Reviewed model card and separately linked operator evidence; not inferred by this builder"}
    return dict(output=output, zip_output=zip_output, operations=operations, config=config, identity=identity,
                adapter=adapter, pins=_pins, summary=summary, source_snapshots={path:snapshot(path) for path, _ in operations.values()})


def validate_adapter(prepared):
    """CPU tensor-only audit; never construct GPT or open original weight files."""
    os.environ["CUDA_VISIBLE_DEVICES"] = ""
    import torch
    require(not torch.cuda.is_initialized(), "Use a CPU-only builder process without an existing CUDA context")
    torch.set_num_threads(1)
    from hi_h200_native.adapter_synth import read_pure_payload
    payload, _ = read_pure_payload(prepared["adapter"], prepared["summary"]["adapter_sha256"], prepared["identity"], prepared["config"])
    spec, pins = payload["adapter_spec"], prepared["pins"]
    require(payload["step"] == pins.step, "Actual adapter step differs from frozen selection")
    parameters = pure_parameters(spec, prepared["config"])
    dim, rank = pins.model_dim, parameters["lora_rank"]
    expected = {}
    for target in spec["lora_targets"]:
        width = 3 * dim if target.endswith(".c_attn") else dim
        expected["base." + target + ".lora_A"] = (rank, dim)
        expected["base." + target + ".lora_B"] = (width, rank)
    state = payload["trainable"]
    require(isinstance(state, dict) and set(state) == set(expected) and len(expected) == pins.layers * 4,
            "Adapter must contain exactly the complete pure A/B inventory, without embeddings/heads")
    for name, shape in expected.items():
        tensor = state[name]
        require(torch.is_tensor(tensor) and tensor.layout == torch.strided and tensor.device.type == "cpu"
                and tensor.dtype == torch.float32 and tuple(tensor.shape) == shape and torch.isfinite(tensor).all().item(),
                "Invalid finite CPU FP32 A/B tensor")
    return {"format": spec["format"], "training_profile": spec["training_profile"], "adapter_spec": spec,
            "adapter_tensor_validation": True, "trainable_tensors": len(expected),
            "trainable_parameters": sum(tensor.numel() for tensor in state.values()), "tensor_audit_device": "cpu"}


def verify_package(root, payloads):
    """Check only the literal expected tree; unknown files/dirs/symlinks are rejected."""
    all_names = set(payloads) | {"manifest.json", "SHA256SUMS", "COMPLETE.json"}
    directories = {""}
    for name in all_names:
        directories.update(str(parent) for parent in Path(name).parents if str(parent) != ".")
    for relative in directories:
        folder = root / relative
        require(not folder.is_symlink() and folder.is_dir(), "Invalid release directory")
        expected = {Path(name).relative_to(relative).parts[0] for name in all_names if relative == "" or Path(name).is_relative_to(relative)}
        require({child.name for child in folder.iterdir()} == expected, "Unexpected file or directory in public package")
    manifest = public.bounded_json(root / "manifest.json")
    require(set(manifest) == {"schema_version", "files"} and manifest["schema_version"] == 1 and set(manifest["files"]) == set(payloads), "Invalid release payload manifest")
    for name in all_names:
        path = root / name
        require(path.is_file() and not path.is_symlink(), "Package entries must be regular files")
        if name in payloads:
            require(manifest["files"][name] == {"bytes":path.stat().st_size, "sha256":synth.sha256(path)}, "Public package payload changed")
    sums = "".join(synth.sha256(root / name) + "  " + name + "\n" for name in sorted(set(payloads) | {"manifest.json"}))
    require((root / "SHA256SUMS").read_text() == sums, "Public checksum inventory differs")
    require(public.bounded_json(root / "COMPLETE.json") == {"schema_version":1, "manifest_sha256":synth.sha256(root / "manifest.json"),
                "sha256sums_sha256":synth.sha256(root / "SHA256SUMS")}, "Public package is incomplete")
    return len(all_names)


def build(prepared):
    # All data/schema/license/document validation precedes any output creation.
    audit = validate_adapter(prepared)
    summary = dict(prepared["summary"], **audit)
    generated = {"adapter-config.json": encode(audit["adapter_spec"]), "public-summary.json": encode(summary),
        "release.json": encode(dict(summary, kind="experimental_native_pure_attention_lora", quality_verified=False,
                                    builder_sha256=synth.sha256(Path(__file__)))),
        "NON_ENDORSEMENT.txt": public.NON_ENDORSEMENT.encode(), "DATA_ATTRIBUTION.md":public.ATTRIBUTION.encode(),
        "BASE_METADATA.md": BASE_NOTE.encode()}
    operations, output = prepared["operations"], prepared["output"]
    require(not set(operations) & set(generated), "Duplicate release destinations")
    require(all(snapshot(path) == before for path, before in prepared["source_snapshots"].items()), "Release input changed after validation")
    size = sum(path.stat().st_size for path, _ in operations.values()) + sum(map(len, generated.values()))
    require(size < 64 * 1024**2 and shutil.disk_usage(output.parent).free >= size * (2 if prepared["zip_output"] else 1) + 256 * 1024**2,
            "Insufficient disk headroom or oversized small package")
    output.mkdir(mode=0o700, exist_ok=False)
    for name, (path, digest) in operations.items():
        target = output / name
        target.parent.mkdir(parents=True, exist_ok=True)
        public.copy_verified(path, target, digest, path.stat().st_size)
    for name, content in generated.items():
        with (output / name).open("xb") as stream:
            stream.write(content); stream.flush(); os.fsync(stream.fileno())
    payloads = set(operations) | set(generated)
    files = {name:{"bytes":(output / name).stat().st_size, "sha256":synth.sha256(output / name)} for name in sorted(payloads)}
    for name, content in (("manifest.json", encode({"schema_version":1, "files":files})),
        ("SHA256SUMS", "".join(synth.sha256(output / item) + "  " + item + "\n" for item in sorted(payloads)).encode())):
        if name == "SHA256SUMS":
            content = "".join(synth.sha256(output / item) + "  " + item + "\n" for item in sorted(payloads | {"manifest.json"})).encode()
        with (output / name).open("xb") as stream:
            stream.write(content); stream.flush(); os.fsync(stream.fileno())
    complete = {"schema_version":1, "manifest_sha256":synth.sha256(output / "manifest.json"), "sha256sums_sha256":synth.sha256(output / "SHA256SUMS")}
    with (output / "COMPLETE.json").open("xb") as stream:
        stream.write(encode(complete)); stream.flush(); os.fsync(stream.fileno())
    count = verify_package(output, payloads)
    require(all(snapshot(path) == before for path, before in prepared["source_snapshots"].items()), "Release input changed while copying")
    result = dict(status="pure_lora_public_package_verified_not_published", files=count,
        adapter_sha256=summary["adapter_sha256"], adapter_bytes=summary["adapter_bytes"], adapter_tensor_validation=True,
        quality_verified=False, production_deployed=False, uploaded=False, gpu_used=False)
    if prepared["zip_output"]:
        with prepared["zip_output"].open("xb") as stream:
            with zipfile.ZipFile(stream, "w", compression=zipfile.ZIP_STORED, allowZip64=False) as archive:
                for name in sorted(payloads | {"manifest.json", "SHA256SUMS", "COMPLETE.json"}):
                    archive.write(output / name, name)
            stream.flush(); os.fsync(stream.fileno())
        with zipfile.ZipFile(prepared["zip_output"]) as archive:
            entries = archive.infolist()
            all_names = payloads | {"manifest.json", "SHA256SUMS", "COMPLETE.json"}
            require(len(entries) == len(all_names) and {item.filename for item in entries} == all_names,
                    "Small archive inventory differs")
            for item in entries:
                require(item.compress_type == zipfile.ZIP_STORED and not item.flag_bits & 1
                        and item.file_size == (output / item.filename).stat().st_size, "Small archive entry differs")
                with archive.open(item) as stream:
                    digest = hashlib.sha256()
                    for block in iter(lambda: stream.read(1024 * 1024), b""):
                        digest.update(block)
                require(digest.hexdigest() == synth.sha256(output / item.filename), "Small archive payload changed")
        result.update(zip_sha256=synth.sha256(prepared["zip_output"]), zip_bytes=prepared["zip_output"].stat().st_size)
    descriptor = os.open(output, os.O_RDONLY)
    try: os.fsync(descriptor)
    finally: os.close(descriptor)
    return result


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, allow_abbrev=False)
    for name in ("workspace-root", "official-repo", "model-dir", "base-manifest", "adapter", "model-card", "output-dir"):
        parser.add_argument("--" + name, type=Path, required=True)
    for name in ("adapter-sha256", "base-manifest-sha256", "model-card-sha256"):
        parser.add_argument("--" + name, required=True)
    parser.add_argument("--zip-output", type=Path)
    parser.add_argument("--execute", action="store_true")
    args = parser.parse_args(argv)
    try:
        prepared = inspect(args)
        result = build(prepared) if args.execute else dict(prepared["summary"], status="metadata_verified_tensor_audit_pending_no_output", uploaded=False)
        print(json.dumps(result, sort_keys=True, allow_nan=False))
        return 0
    except (OSError, ValueError, RuntimeError, ImportError, KeyError) as exc:
        print(json.dumps({"status":"release_blocked_not_published", "failure_type":type(exc).__name__, "uploaded":False,
                          "quality_verified":False, "gpu_used":False}), file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
