#!/usr/bin/env python3
"""Build a fixed, whitelist-only experimental pure LoRA package; never publish.

Default verifies local metadata/hashes without Torch or writes. --execute reads
only the independently pinned adapter with restricted CPU Torch loading. Original
GPT/acoustic weights are not opened or copied; their pinned hashes are references.
"""
